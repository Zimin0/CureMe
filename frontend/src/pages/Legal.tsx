function Doc({ title, children }: { title: string; children: ReactNode }) {
  const nav = useNavigate()
  return (
    <div className="legal-wrap">
      <article className="legal card stack">
        <button className="btn ghost sm" style={{ alignSelf: 'flex-start' }} onClick={() => (history.length > 1 ? nav(-1) : nav('/'))}>
          <ArrowLeft size={16} />Назад
        </button>
        <h1>{title}</h1>
        <p className="muted small">Редакция от {LEGAL_DATE}</p>
        {children}
        <LegalLinks />
      </article>
    </div>
  )
}

